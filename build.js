#!/usr/bin/env node
////////////////////////////////////////////////////////////////////////////
// Dependency-free bundler for this extension (no npm install needed).
//
//   node build.js
//
// Follows the relative ES-module imports from src/content-script.js and
// writes dist/bundle.js as one IIFE. Each module gets its own scope, so
// modules can reuse names (e.g. classic/ and utils/ both export colorPlayers).
// Supports the import/export forms used in this repo:
//   import { a, b as c } from "./x";
//   export function f() {}   export const x = ...   export let / class
////////////////////////////////////////////////////////////////////////////
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const ENTRY = path.join(ROOT, 'src', 'content-script.js');
const OUT = path.join(ROOT, 'dist', 'bundle.js');

const modules = new Map(); // abs path -> { id, code }
const order = [];

function resolve(fromFile, spec) {
    let p = path.resolve(path.dirname(fromFile), spec);
    if (!p.endsWith('.js')) p += '.js';
    if (!fs.existsSync(p)) throw new Error(`Cannot resolve "${spec}" from ${path.relative(ROOT, fromFile)}`);
    return p;
}

function load(file) {
    if (modules.has(file)) return modules.get(file);
    const id = `__mod${modules.size}`;
    const entry = { id, code: null };
    modules.set(file, entry);

    let src = fs.readFileSync(file, 'utf8');
    const exportsList = [];

    // imports -> destructure from the dependency's exports object
    src = src.replace(/^import\s*\{([^}]*)\}\s*from\s*["']([^"']+)["'];?\s*$/gm, (_, names, spec) => {
        const dep = load(resolve(file, spec));
        const bindings = names.split(',').map(s => s.trim()).filter(Boolean)
            .map(n => n.replace(/\s+as\s+/, ': '));
        return `const { ${bindings.join(', ')} } = ${dep.id};`;
    });
    if (/^import\s/m.test(src)) throw new Error(`Unsupported import form in ${path.relative(ROOT, file)}`);

    // exports -> plain declarations, remembered for the exports object
    src = src.replace(/^export\s+(async\s+function|function|const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm,
        (_, kind, name) => { exportsList.push(name); return `${kind} ${name}`; });
    if (/^export\s/m.test(src)) throw new Error(`Unsupported export form in ${path.relative(ROOT, file)}`);

    entry.code =
        `// ${path.relative(ROOT, file)}\n` +
        `const ${id} = (() => {\n${src}\nreturn { ${exportsList.join(', ')} };\n})();\n`;
    order.push(file); // dependencies are pushed before dependents
    return entry;
}

load(ENTRY);

const bundle =
    `// Generated by build.js - do not edit. Run \`node build.js\` to rebuild.\n` +
    `(() => {\n"use strict";\n${order.map(f => modules.get(f).code).join('\n')}})();\n`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, bundle);
// The old webpack source map no longer matches; remove it so DevTools doesn't use it.
const staleMap = OUT + '.map';
if (fs.existsSync(staleMap)) fs.unlinkSync(staleMap);

console.log(`Wrote ${path.relative(ROOT, OUT)} (${order.length} modules, ${bundle.length} bytes)`);
order.forEach(f => console.log('  ' + path.relative(ROOT, f)));
